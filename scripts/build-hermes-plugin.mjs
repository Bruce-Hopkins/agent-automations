import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outfile = path.join(root, 'hermes-plugin', 'dist', 'server.mjs');
const noticesFile = path.join(root, 'hermes-plugin', 'dist', 'THIRD_PARTY_NOTICES.md');
const { version } = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

try {
  const result = await build({
    entryPoints: [path.join(root, 'src', 'mcp', 'main.ts')],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    outfile,
    logLevel: 'warning',
    metafile: true,
    define: { __LEAFI_VERSION__: JSON.stringify(version) },
    banner: {
      js: "import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);",
    },
  });
  fs.writeFileSync(noticesFile, thirdPartyNotices(result.metafile));
  process.stderr.write(`Built ${path.relative(root, outfile)} and ${path.relative(root, noticesFile)}\n`);
} catch (error) {
  process.stderr.write(`Bundle failed: ${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
}

/**
 * The bundle carries third-party code, and MIT/Apache/BSD/ISC licenses require
 * their notices to travel with it. Every package that contributed an input
 * file is listed with its license text.
 */
function thirdPartyNotices(metafile) {
  const packages = new Map();
  for (const input of Object.keys(metafile.inputs)) {
    const dir = packageDir(path.resolve(root, input));
    if (dir && !packages.has(dir)) {
      packages.set(dir, readPackage(dir));
    }
  }

  const entries = [...packages.values()]
    .filter((entry) => entry.name !== 'leafi')
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  const unique = entries.filter(
    (entry, index) => index === 0 || entry.name !== entries[index - 1].name || entry.version !== entries[index - 1].version,
  );

  const sections = unique.map((entry) => {
    const header = `## ${entry.name}@${entry.version}\n\nLicense: ${entry.license}`;
    const body = entry.text
      ? `\n\n\`\`\`text\n${entry.text.trim()}\n\`\`\``
      : '\n\nNo license file is included in the package; see its `license` field above.';
    return `${header}${body}`;
  });

  return (
    '# Third-party notices\n\n' +
    '`server.mjs` bundles the following packages. Their licenses and notices are reproduced below.\n' +
    'This file is generated by `scripts/build-hermes-plugin.mjs`; do not edit it by hand.\n\n' +
    `${sections.join('\n\n')}\n`
  );
}

/** The nearest directory above `file` with a package.json that names a package. */
function packageDir(file) {
  let dir = path.dirname(file);
  while (dir !== path.dirname(dir)) {
    const manifest = path.join(dir, 'package.json');
    if (fs.existsSync(manifest)) {
      const parsed = JSON.parse(fs.readFileSync(manifest, 'utf8'));
      if (typeof parsed.name === 'string' && typeof parsed.version === 'string') {
        return dir;
      }
    }
    dir = path.dirname(dir);
  }
  return undefined;
}

function readPackage(dir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const license =
    typeof manifest.license === 'string'
      ? manifest.license
      : manifest.license?.type ?? (Array.isArray(manifest.licenses) ? manifest.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN');
  const files = fs
    .readdirSync(dir)
    .filter((name) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(name))
    .sort();
  const text = files.map((name) => fs.readFileSync(path.join(dir, name), 'utf8')).join('\n\n');
  return { name: manifest.name, version: manifest.version, license, text };
}
